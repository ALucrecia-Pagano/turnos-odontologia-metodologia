from collections.abc import Sequence
from datetime import datetime
from typing import Protocol
from uuid import UUID

from app.domain.catalog.result import CatalogResult
from app.domain.model import (
    Appointment,
    Block,
    Chair,
    Patient,
    Professional,
    Service,
    WorkingHours,
)


class ProfessionalRepository(Protocol):
    def create(self, candidate: Professional) -> CatalogResult[Professional]: ...
    def deactivate(self, identifier: UUID) -> CatalogResult[Professional] | None: ...
    def reactivate(self, identifier: UUID) -> CatalogResult[Professional] | None: ...
    def get_by_id(self, identifier: UUID) -> Professional | None: ...
    def list(self) -> Sequence[Professional]: ...


class ChairRepository(Protocol):
    def create(self, candidate: Chair) -> CatalogResult[Chair]: ...
    def deactivate(self, identifier: UUID) -> CatalogResult[Chair] | None: ...
    def reactivate(self, identifier: UUID) -> CatalogResult[Chair] | None: ...
    def get_by_id(self, identifier: UUID) -> Chair | None: ...
    def list(self) -> Sequence[Chair]: ...


class ServiceRepository(Protocol):
    def create(self, candidate: Service) -> CatalogResult[Service]: ...
    def deactivate(self, identifier: UUID) -> CatalogResult[Service] | None: ...
    def reactivate(self, identifier: UUID) -> CatalogResult[Service] | None: ...
    def get_by_id(self, identifier: UUID) -> Service | None: ...
    def list(self) -> Sequence[Service]: ...


class PatientRepository(Protocol):
    def create(self, candidate: Patient) -> CatalogResult[Patient]: ...
    def get_by_id(self, identifier: UUID) -> Patient | None: ...
    def list(self) -> Sequence[Patient]: ...


class AppointmentReader(Protocol):
    def list_for_professional_in_range(
        self,
        professional_id: UUID,
        start_at: datetime,
        end_at: datetime,
    ) -> Sequence[Appointment]: ...


class WorkingHoursRepository(Protocol):
    def replace_for_professional(
        self, professional_id: UUID, slots: Sequence[WorkingHours]
    ) -> CatalogResult[tuple[WorkingHours, ...]]: ...
    def list_by_professional(self, professional_id: UUID) -> tuple[WorkingHours, ...]: ...
    def list(self) -> tuple[WorkingHours, ...]: ...


class BlockRepository(Protocol):
    def create(self, candidate: Block) -> CatalogResult[Block]: ...
    def delete(self, identifier: UUID) -> Block | None: ...
    def get_by_id(self, identifier: UUID) -> Block | None: ...
    def list_by_professional(self, professional_id: UUID) -> tuple[Block, ...]: ...
    def list(self) -> tuple[Block, ...]: ...
    def list_affected_appointments(self, block: Block) -> tuple[Appointment, ...]: ...
